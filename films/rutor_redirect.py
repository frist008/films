"""R340: links to rutor releases that survive a dead rutor.info — a redirect page on the project's GitHub Pages.

Owner, 2026-11-23: «и для ссылок с рутором не рабочими надо добавить авто перенаправление если не работает ссылка как ты
делал». rutor.info / rutor.is go down; the mirrors of config/settings.toml [rutor] mirrors have the same release numbers
(rutor.org is NOT a mirror — a paid site of another owner). The sheet links a rutor release to
`docs/rutor.html#<номер>` (`[rutor] redirect_page`); the page probes the mirrors in their order and opens the release on the
first live one, else it lists links to every mirror.

How the page probes: the page is https, the mirrors are http — `fetch()` of http from https is blocked (mixed content) and
browsers auto-upgrade a mixed-content image to https, so each mirror is probed by loading its favicon as an image over
https and over http (3.5 s timeout). A loaded image = the mirror is up (and the scheme that loaded is the one opened).
Nothing loaded in time → the page shows every mirror as a link.

    python -X utf8 -m films.rutor_redirect build   # (re)write docs/rutor.html from [rutor] mirrors
    python -X utf8 -m films.rutor_redirect check   # exit 1 when docs/rutor.html differs from [rutor] mirrors

The page works only after it is pushed to GitHub (GitHub Pages publishes docs/ of main).
"""
import json
import re
import sys
from functools import lru_cache

from . import db, rank

PAGE = db.ROOT / "docs" / "rutor.html"
_ID_RE = re.compile(r"/torrent/([0-9]+)")


def mirrors() -> list[str]:
    """[rutor] mirrors in their order (the same list the collector uses, films.sources.rutor.mirrors without the env pin)."""
    cfg = rank.settings().get("rutor", {})
    return [m.rstrip("/") for m in cfg.get("mirrors") or [cfg.get("base", "http://rutor.info")]]


@lru_cache(maxsize=1)
def github_owner() -> str | None:
    """Owner of the GitHub repository from .git/config remote origin (git@github.com:<owner>/films.git or
    https://github.com/<owner>/films) — the login is not written into tracked files."""
    try:
        text = (db.ROOT / ".git" / "config").read_text(encoding="utf-8")
    except OSError:
        return None
    sec = re.search(r'\[remote "origin"\]([^\[]*)', text)
    m = sec and re.search(r"url\s*=\s*\S*github\.com[:/]([A-Za-z0-9-]+)/", sec.group(1))
    return m.group(1) if m else None


def page_url() -> str | None:
    """Address of the redirect page ([rutor] redirect_page, «{github}» = the repository owner); None = no page (the sheet
    then links rutor directly)."""
    tpl = rank.settings().get("rutor", {}).get("redirect_page")
    if not tpl:
        return None
    if "{github}" in tpl:
        owner = github_owner()
        if not owner:
            return None
        tpl = tpl.replace("{github}", owner.lower())
    return tpl


def release_id(rel: dict) -> str | None:
    """rutor release number: from the URL (http://rutor.info/torrent/<id>), else source_id when it is a number."""
    m = _ID_RE.search(rel.get("url") or "")
    if m:
        return m.group(1)
    sid = str(rel.get("source_id") or "")
    return sid if sid.isdigit() else None


def release_link(rel: dict | None) -> str | None:
    """The link the sheet puts on a release: a rutor release → the redirect page with its number; any other tracker —
    its own URL untouched."""
    if not rel:
        return None
    url = rel.get("url")
    if rel.get("source") != "rutor":
        return url
    rid, page = release_id(rel), page_url()
    return f"{page}#{rid}" if rid and page else url


TEMPLATE = """<!doctype html>
<html lang="ru">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<meta name="robots" content="noindex">
<title>rutor — зеркала</title>
<!-- Generated by `python -X utf8 -m films.rutor_redirect build` from config/settings.toml [rutor] mirrors. Do not edit. -->
<style>
  :root { color-scheme: light dark; --fg: #1d1d1f; --bg: #fafafa; --muted: #666; --link: #0b57d0; }
  @media (prefers-color-scheme: dark) { :root { --fg: #e8e8e8; --bg: #161616; --muted: #9a9a9a; --link: #8ab4f8; } }
  body { margin: 0; padding: 24px 16px; font: 16px/1.5 system-ui, sans-serif; color: var(--fg); background: var(--bg); }
  main { max-width: 560px; margin: 0 auto; }
  a { color: var(--link); }
  .muted { color: var(--muted); }
  li { margin: 6px 0; }
</style>
</head>
<body>
<main>
<h1 style="font-size:20px">Раздача rutor <span id="rid"></span></h1>
<p id="status">Проверяю зеркала…</p>
<ul id="list"></ul>
<noscript><p>Без JavaScript проверка не работает — выберите зеркало вручную (номер раздачи — после «#» в адресе).</p></noscript>
</main>
<script>
(function () {
  var MIRRORS = __MIRRORS__;
  var TIMEOUT = 3500;
  var m = (location.hash.slice(1) || new URLSearchParams(location.search).get("id") || "").match(/^[0-9]+/);
  var id = m ? m[0] : "";
  var status = document.getElementById("status"), list = document.getElementById("list");
  document.getElementById("rid").textContent = id ? "№ " + id : "";
  function host(u) { return u.replace(/^https?:[/][/]/, "").replace(/[/].*$/, ""); }
  function target(base) { return base + (id ? "/torrent/" + id + "/" : "/"); }
  var items = MIRRORS.map(function (u) {
    var li = document.createElement("li"), a = document.createElement("a"), s = document.createElement("span");
    a.href = target(u); a.textContent = host(u); s.className = "muted"; s.textContent = " — проверяю";
    li.appendChild(a); li.appendChild(s); list.appendChild(li);
    return {base: u, host: host(u), a: a, s: s, state: "wait", ok: null};
  });
  if (!id) { status.textContent = "В адресе нет номера раздачи (rutor.html#1234567). Зеркала:"; }
  function probe(it, scheme, done) {
    var img = new Image(), fin = false;
    var t = setTimeout(function () { if (!fin) { fin = true; img.src = ""; done(false); } }, TIMEOUT);
    img.onload = function () { if (!fin) { fin = true; clearTimeout(t); done(true); } };
    img.onerror = function () { if (!fin) { fin = true; clearTimeout(t); done(false); } };
    img.src = scheme + "://" + it.host + "/favicon.ico?_=" + Date.now();
  }
  var gone = false;
  function decide() {
    if (gone) return;
    for (var i = 0; i < items.length; i++) {
      var it = items[i];
      if (it.state === "wait") return;          // an earlier mirror is still being checked: keep the order
      if (it.state === "up") {
        gone = true;
        status.textContent = "Открываю " + it.host + "…";
        if (id) location.replace(target(it.ok + "://" + it.host));
        return;
      }
    }
    status.textContent = "Ни одно зеркало не ответило за " + TIMEOUT / 1000 + " с — попробуйте вручную:";
  }
  items.forEach(function (it) {
    var left = 2, https = null, http = null;
    function one() {
      if (--left) return;
      it.ok = https ? "https" : http ? "http" : null;
      it.state = it.ok ? "up" : "down";
      it.s.textContent = it.ok ? " — работает" : " — не отвечает";
      if (it.ok) it.a.href = target(it.ok + "://" + it.host);
      decide();
    }
    probe(it, "https", function (ok) { https = ok; one(); });
    probe(it, "http", function (ok) { http = ok; one(); });
  });
})();
</script>
</body>
</html>
"""


def render(ms: list[str] | None = None) -> str:
    return TEMPLATE.replace("__MIRRORS__", json.dumps(ms if ms is not None else mirrors()))


def build() -> dict:
    html = render()
    PAGE.parent.mkdir(parents=True, exist_ok=True)
    PAGE.write_text(html, encoding="utf-8", newline="\n")
    return {"page": str(PAGE.relative_to(db.ROOT)), "mirrors": mirrors(), "url": page_url()}


def main(argv: list[str]) -> int:
    cmd = argv[0] if argv else "build"
    if cmd == "build":
        print(json.dumps(build(), ensure_ascii=False))
        return 0
    if cmd == "check":
        ok = PAGE.exists() and PAGE.read_text(encoding="utf-8") == render()
        print(json.dumps({"page_matches_settings": ok, "url": page_url()}, ensure_ascii=False))
        return 0 if ok else 1
    print(__doc__)
    return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
